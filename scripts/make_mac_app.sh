#!/bin/bash
# Build SensiExtractor.app — the macOS double-click launcher with the app icon.
# Called by setup.sh on macOS; safe to re-run (rebuilds the bundle in place).
#
#   bash scripts/make_mac_app.sh <repo_dir> <conda_base>
#
# A .app is just a folder Finder shows as one icon:
#   SensiExtractor.app/Contents/Info.plist        name, icon, bundle id
#   SensiExtractor.app/Contents/MacOS/SensiExtractor   activates ./env, runs gui.py
#   SensiExtractor.app/Contents/Resources/icon.icns    from assets/ (scripts/make_icons.py)
# Machine-specific (bakes in this machine's conda path), so it is git-ignored.
# No Terminal window: GUI output goes to ~/Library/Logs/SensiExtractor.log;
# runGUI.command stays the "with live logs" launcher.
set -e

REPO_DIR="$1"
CONDA_BASE="$2"
if [ -z "$REPO_DIR" ] || [ -z "$CONDA_BASE" ]; then
    echo "usage: bash scripts/make_mac_app.sh <repo_dir> <conda_base>" >&2
    exit 2
fi

APP="$REPO_DIR/SensiExtractor.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$REPO_DIR/assets/icon.icns" "$APP/Contents/Resources/icon.icns"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>
    <string>SensiExtractor</string>
    <key>CFBundleDisplayName</key>
    <string>SensiExtractor</string>
    <key>CFBundleIdentifier</key>
    <string>edneuro.SensiExtractor.GUI</string>
    <key>CFBundleExecutable</key>
    <string>SensiExtractor</string>
    <key>CFBundleIconFile</key>
    <string>icon</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/SensiExtractor" <<LAUNCH
#!/bin/bash
# Auto-generated by scripts/make_mac_app.sh — launches the SensiExtractor GUI.
cd "$REPO_DIR"
source "$CONDA_BASE/etc/profile.d/conda.sh"
conda activate ./env
LOG="\$HOME/Library/Logs/SensiExtractor.log"
mkdir -p "\$(dirname "\$LOG")"
echo "=== \$(date) ===" >> "\$LOG"
# exec: the GUI replaces this script's process, so the Dock entry stays the app's.
exec python gui.py >> "\$LOG" 2>&1
LAUNCH
chmod +x "$APP/Contents/MacOS/SensiExtractor"

# Nudge Finder to pick up the icon of a freshly (re)built bundle.
touch "$APP"
echo "  Created SensiExtractor.app (with icon)."
