#!/bin/bash
# SensiExtractor - First-time setup (macOS / Linux)
# Run from inside the SensiExtractor folder:  bash setup.sh
set -e

echo "============================================================"
echo " SensiExtractor - First-time setup"
echo "============================================================"
echo ""
echo "Everything will be downloaded into this folder:"
echo "  ./env/        Python environment (~6 GB)"
echo "  ./data/mfa_data/   MFA acoustic models (~1 GB)"
echo "  ./data/hf_cache/   GPT-2 / BERT weights (~500 MB, on first run)"
echo ""
read -p "Press Enter to continue (Ctrl+C to cancel)..."

echo ""
echo "[1/5] Installing conda-lock (deterministic installer) ..."
conda install -n base -c conda-forge conda-lock -y

echo ""
echo "[2/5] Creating ./env from conda-lock.yml (exact, pinned versions) ..."
# conda-lock.yml pins every package for this platform. CPU Kaldi is pinned in
# environment.yml; the lock captures it exactly.
conda-lock install -p ./env conda-lock.yml

echo ""
echo "[3/5] Downloading MFA models into ./data/mfa_data ..."
conda run --prefix ./env python scripts/download_models.py

echo ""
echo "[4/5] Downloading spaCy model into ./env ..."
conda run --prefix ./env python -m spacy download en_core_web_sm

echo ""
echo "[5/5] Creating the double-click launcher ..."
# Generate a launcher tailored to THIS machine. We bake in the conda base path
# we just used, because a double-clicked launcher starts in a bare shell that
# does NOT load your 'conda init' setup — so it can't find conda on its own.
# It runs the GUI with the terminal attached, so you see live logs. Regenerated
# on every setup; machine-specific, so it is git-ignored.
CONDA_BASE="$(conda info --base)"
REPO_DIR="$(cd "$(dirname "$0")" && pwd)"
case "$(uname -s)" in
    Darwin) LAUNCHER="runGUI.command" ;;   # macOS: double-clickable in Finder
    *)      LAUNCHER="runGUI.sh" ;;         # Linux
esac
cat > "$REPO_DIR/$LAUNCHER" <<LAUNCH
#!/bin/bash
# Auto-generated by setup.sh — launches the SensiExtractor GUI.
# Machine-specific (contains your conda path); NOT committed. Re-run setup.sh to regenerate.
cd "\$(dirname "\$0")"
source "$CONDA_BASE/etc/profile.d/conda.sh"
conda activate ./env
python gui.py
echo ""
read -n 1 -s -r -p "GUI closed. Press any key to close this window."
echo ""
LAUNCH
chmod +x "$REPO_DIR/$LAUNCHER"

# macOS: also build SensiExtractor.app, which carries the app icon (a .command
# can't). runGUI.command stays as the launcher that shows live logs in Terminal.
if [ "$(uname -s)" = "Darwin" ]; then
    bash "$REPO_DIR/scripts/make_mac_app.sh" "$REPO_DIR" "$CONDA_BASE"
fi

# Linux: also drop a .desktop entry so it shows the app icon (an icon can't
# attach to a bare .sh). Terminal=true keeps the log window open.
if [ "$(uname -s)" = "Linux" ]; then
    cat > "$REPO_DIR/SensiExtractor.desktop" <<DESK
[Desktop Entry]
Type=Application
Name=SensiExtractor
Comment=Word-level EEG stimulus feature extraction
Exec=$REPO_DIR/runGUI.sh
Icon=$REPO_DIR/assets/icon.png
Path=$REPO_DIR
Terminal=true
Categories=Science;Education;
DESK
    chmod +x "$REPO_DIR/SensiExtractor.desktop"
fi

echo ""
echo "============================================================"
echo " Setup complete!"
echo ""
echo " To launch the app, either:"
if [ "$(uname -s)" = "Darwin" ]; then
    echo "   - double-click  SensiExtractor   (the app icon in Finder), or"
fi
echo "   - double-click  $LAUNCHER   (in your file browser; shows live logs), or"
echo "   - run:  conda activate ./env  &&  python gui.py"
echo "============================================================"
